const pool = require('../config/database');
const HttpError = require('../utils/httpError');

// Course completion certificates, approved by an Admin.
//
// "Completed" is the existing definition: an enrolment whose status is 'completed' (the
// course has topics and the student finished all of them). Completion no longer issues a
// certificate. It creates a certificate REQUEST (certificate_requests, status 'pending'), in the
// same transaction as the status change. Only an Admin approving the request creates the
// certificate row, so a pending or rejected request exposes no certificate at all.
//
//   * at most one pending request per (student, course): a partial unique index, and every insert
//     uses ON CONFLICT DO NOTHING, so repeated or concurrent requests never duplicate;
//   * at most one certificate per (student, course): the existing unique constraint, and approval
//     is refused when one already exists (active or revoked);
//   * a rejected request is kept as history and does not block a new request while the course is
//     still completed;
//   * a decision is made on a locked row, so two Admins deciding at once are applied in turn.
// Certificate numbers are generated by the database and never come from a client.
//
// Enrolments that were already completed before this workflow, and all existing certificates,
// are left alone: nothing is back-filled, revoked or re-issued. A legacy completed student asks
// for a certificate explicitly (requestForStudent) and it then follows the same approval.

// `db` is the pool or a transaction client; `enrolmentIds` are enrolments that have just
// become completed. Only Students are asked for (a user later made Trainer/Admin gets nothing),
// and a student who already has a certificate for the course (any status) gets no new request.
// Returns the number of requests created.
async function requestForEnrolments(db, enrolmentIds) {
  if (enrolmentIds.length === 0) return 0;
  const { rowCount } = await db.query(
    `INSERT INTO certificate_requests (student_id, course_id, enrolment_id)
     SELECT e.student_id, e.course_id, e.id
     FROM enrolments e
     JOIN users u ON u.id = e.student_id AND u.role = 'student'
     WHERE e.id = ANY($1::bigint[]) AND e.status = 'completed'
       AND NOT EXISTS (SELECT 1 FROM certificates c WHERE c.student_id = e.student_id AND c.course_id = e.course_id)
     ON CONFLICT (student_id, course_id) WHERE status = 'pending' DO NOTHING`,
    [enrolmentIds]
  );
  return rowCount;
}

const SELECT = `
  SELECT ct.id, ct.certificate_number, ct.student_id, ct.course_id, ct.student_name, ct.course_title,
         ct.issued_at, ct.status, ct.revoked_at, ct.revocation_reason,
         u.email AS student_email, rb.full_name AS revoked_by_name
  FROM certificates ct
  JOIN users u ON u.id = ct.student_id
  LEFT JOIN users rb ON rb.id = ct.revoked_by`;

// What a Student (or anyone printing it) sees: the issued facts and the status. The
// revocation reason and who revoked are for Admin only.
function toCertificate(row) {
  return {
    id: row.id,
    certificateNumber: row.certificate_number,
    studentName: row.student_name,
    courseTitle: row.course_title,
    issuedAt: row.issued_at,
    status: row.status,
    revokedAt: row.revoked_at,
  };
}

function toAdminCertificate(row) {
  return {
    ...toCertificate(row),
    studentId: row.student_id,
    studentEmail: row.student_email,
    courseId: row.course_id,
    revokedByName: row.revoked_by_name,
    revocationReason: row.revocation_reason,
  };
}

// ---------------------------------------------------------------------------
// Student: always the signed-in student; another student's id looks like "not found".
// ---------------------------------------------------------------------------

async function listForStudent(studentId) {
  const { rows } = await pool.query(`${SELECT} WHERE ct.student_id = $1 ORDER BY ct.issued_at DESC, ct.id DESC`, [studentId]);
  return rows.map(toCertificate);
}

async function getForStudent(studentId, id) {
  const { rows } = await pool.query(`${SELECT} WHERE ct.id = $1 AND ct.student_id = $2`, [id, studentId]);
  if (!rows[0]) throw new HttpError(404, 'Certificate not found');
  return toCertificate(rows[0]);
}

// The student's certificate for a course, if any (shown on the learning page).
async function findForStudentCourse(studentId, courseId, db = pool) {
  const { rows } = await db.query('SELECT id, certificate_number, status FROM certificates WHERE student_id = $1 AND course_id = $2', [
    studentId,
    courseId,
  ]);
  return rows[0] ? { id: rows[0].id, certificateNumber: rows[0].certificate_number, status: rows[0].status } : null;
}

// ---------------------------------------------------------------------------
// Admin
// ---------------------------------------------------------------------------

async function listForAdmin({ courseId, studentId, status } = {}) {
  const where = [];
  const params = [];
  if (courseId) {
    params.push(courseId);
    where.push(`ct.course_id = $${params.length}`);
  }
  if (studentId) {
    params.push(studentId);
    where.push(`ct.student_id = $${params.length}`);
  }
  if (status) {
    params.push(status);
    where.push(`ct.status = $${params.length}`);
  }
  const { rows } = await pool.query(
    `${SELECT} ${where.length ? `WHERE ${where.join(' AND ')}` : ''} ORDER BY ct.issued_at DESC, ct.id DESC`,
    params
  );
  return rows.map(toAdminCertificate);
}

async function getForAdmin(id) {
  const { rows } = await pool.query(`${SELECT} WHERE ct.id = $1`, [id]);
  if (!rows[0]) throw new HttpError(404, 'Certificate not found');
  return toAdminCertificate(rows[0]);
}

// Revocation keeps the certificate; it records who, when and why. It cannot be undone.
async function revoke(adminId, id, reason) {
  const { rows } = await pool.query(
    `UPDATE certificates SET status = 'revoked', revoked_at = now(), revoked_by = $2, revocation_reason = $3
     WHERE id = $1 AND status = 'active' RETURNING id`,
    [id, adminId, reason]
  );
  if (!rows[0]) {
    await getForAdmin(id); // 404 when it does not exist
    throw new HttpError(409, 'This certificate is already revoked');
  }
  return getForAdmin(id);
}

