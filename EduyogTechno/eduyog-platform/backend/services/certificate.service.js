const REQUEST_SELECT = `
  SELECT r.id, r.student_id, r.course_id, r.status, r.requested_at, r.decided_at, r.decision_reason,
         r.certificate_id, u.full_name AS student_name, u.email AS student_email, c.title AS course_title,
         d.full_name AS decided_by_name
  FROM certificate_requests r
  JOIN users u ON u.id = r.student_id
  JOIN courses c ON c.id = r.course_id
  LEFT JOIN users d ON d.id = r.decided_by`;

// The student sees the state and, for a rejection, the reason; never who decided.
function toRequest(row) {
  return {
    id: row.id,
    courseId: row.course_id,
    courseTitle: row.course_title,
    status: row.status,
    requestedAt: row.requested_at,
    decidedAt: row.decided_at,
    decisionReason: row.status === 'rejected' ? row.decision_reason : null,
    certificateId: row.certificate_id,
  };
}

function toAdminRequest(row) {
  return {
    ...toRequest(row),
    studentId: row.student_id,
    studentName: row.student_name,
    studentEmail: row.student_email,
    decidedByName: row.decided_by_name,
  };
}

// The student's most recent request for a course (shown on the learning page).
async function findRequestForStudentCourse(studentId, courseId, db = pool) {
  const { rows } = await db.query(
    `${REQUEST_SELECT} WHERE r.student_id = $1 AND r.course_id = $2 ORDER BY r.requested_at DESC, r.id DESC LIMIT 1`,
    [studentId, courseId]
  );
  return rows[0] ? toRequest(rows[0]) : null;
}

async function listRequestsForStudent(studentId) {
  const { rows } = await pool.query(`${REQUEST_SELECT} WHERE r.student_id = $1 ORDER BY r.requested_at DESC, r.id DESC`, [
    studentId,
  ]);
  return rows.map(toRequest);
}

// A student asks for the certificate of a course they have completed (the normal request is made
// automatically on completion; this covers a rejected request and legacy completions). Repeating the
// call while a request is pending returns that request. Returns { request, created }.
async function requestForStudent(studentId, courseId) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    // Serialise this student's requests for the course.
    await client.query('SELECT id FROM users WHERE id = $1 FOR UPDATE', [studentId]);
    const { rows: enrolments } = await client.query(
      "SELECT id FROM enrolments WHERE student_id = $1 AND course_id = $2 AND status = 'completed'",
      [studentId, courseId]
    );
    if (!enrolments[0]) {
      throw new HttpError(409, 'You can request a certificate once you have completed the course');
    }
    const existing = await client.query('SELECT id FROM certificates WHERE student_id = $1 AND course_id = $2', [
      studentId,
      courseId,
    ]);
    if (existing.rows[0]) {
      throw new HttpError(409, 'A certificate has already been issued for this course');
    }
    const created = (await requestForEnrolments(client, [enrolments[0].id])) > 0;
    const request = await findRequestForStudentCourse(studentId, courseId, client);
    await client.query('COMMIT');
    return { request, created };
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

async function listRequestsForAdmin({ status } = {}) {
  const { rows } = await pool.query(
    `${REQUEST_SELECT} ${status ? 'WHERE r.status = $1' : ''} ORDER BY r.requested_at DESC, r.id DESC`,
    status ? [status] : []
  );
  return rows.map(toAdminRequest);
}

// Locks one request for a decision; 404 when missing, 409 unless it is still pending.
async function lockPendingRequest(client, id) {
  const { rows } = await client.query(
    'SELECT id, student_id, course_id, status FROM certificate_requests WHERE id = $1 FOR UPDATE',
    [id]
  );
  if (!rows[0]) throw new HttpError(404, 'Certificate request not found');
  if (rows[0].status !== 'pending') throw new HttpError(409, `This request has already been ${rows[0].status}`);
  return rows[0];
}

// Approval creates the certificate (the only place one is created) in the same transaction that
// marks the request approved. It is refused if the student no longer has a completed enrolment or
// a certificate for the course exists already.
async function approveRequest(adminId, id) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const request = await lockPendingRequest(client, id);
    const { rows: eligible } = await client.query(
      `SELECT 1 FROM enrolments e JOIN users u ON u.id = e.student_id AND u.role = 'student'
       WHERE e.student_id = $1 AND e.course_id = $2 AND e.status = 'completed'`,
      [request.student_id, request.course_id]
    );
    if (eligible.length === 0) {
      throw new HttpError(409, 'The student has not completed this course (any more), so no certificate can be issued');
    }
    const { rows: created } = await client.query(
      `INSERT INTO certificates (student_id, course_id, student_name, course_title)
       SELECT u.id, c.id, u.full_name, c.title FROM users u, courses c WHERE u.id = $1 AND c.id = $2
       ON CONFLICT (student_id, course_id) DO NOTHING
       RETURNING id`,
      [request.student_id, request.course_id]
    );
    if (!created[0]) {
      throw new HttpError(409, 'A certificate already exists for this student and course');
    }
    await client.query(
      `UPDATE certificate_requests
       SET status = 'approved', decided_at = now(), decided_by = $2, certificate_id = $3
       WHERE id = $1`,
      [id, adminId, created[0].id]
    );
    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
  return getRequestForAdmin(id);
}

async function rejectRequest(adminId, id, reason) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await lockPendingRequest(client, id);
    await client.query(
      "UPDATE certificate_requests SET status = 'rejected', decided_at = now(), decided_by = $2, decision_reason = $3 WHERE id = $1",
      [id, adminId, reason]
    );
    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
  return getRequestForAdmin(id);
}

async function getRequestForAdmin(id) {
  const { rows } = await pool.query(`${REQUEST_SELECT} WHERE r.id = $1`, [id]);
  if (!rows[0]) throw new HttpError(404, 'Certificate request not found');
  return toAdminRequest(rows[0]);
}

